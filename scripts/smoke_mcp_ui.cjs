/* Browser acceptance against an isolated real stdio MCP store. Never use a personal store. */
const fs = require("node:fs/promises");
const path = require("node:path");
const assert = require("node:assert/strict");
const { chromium } = require(process.env.RUMINATE_PLAYWRIGHT_MODULE || "playwright");

(async () => {
  const base = process.argv[2] || "http://127.0.0.1:8767";
  const output = path.resolve(process.argv[3] || ".local/mcp-ui-browser");
  await fs.mkdir(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, executablePath: process.env.RUMINATE_BROWSER_EXECUTABLE || undefined });
  const page = await browser.newPage({ viewport: { width: 1180, height: 960 } });
  const failures = [], iframeRequests = [];
  page.on("pageerror", error => failures.push(String(error)));
  page.on("request", request => { if (request.frame().parentFrame() && request.resourceType() !== "document") iframeRequests.push(request.url()); });
  const name = `MCP 界面验收 ${Date.now()}`;
  const fixture = path.join(output, "synthetic-note.md");
  const quote = "Evidence survives 😀 across sessions.";
  await fs.writeFile(fixture, `# MCP GUI fixture ${name}\n\n${quote}\n`);
  const call = (tool, args) => page.evaluate(async ({ tool, args }) => {
    const response = await fetch("/call", { method: "POST", headers: { "Content-Type": "application/json", "X-Harness-Token": token }, body: JSON.stringify({ name: tool, arguments: args }) });
    const result = await response.json();
    if (!response.ok || result.isError) throw Error(JSON.stringify(result));
    return result.structuredContent;
  }, { tool, args });
  const read = async (action, params = {}) => (await call("ui_read", { action, params })).data;
  const write = async (action, params = {}) => (await call("ui_write", { action, params: { ...params, request_id: `${name}-${action}-${Date.now()}` } })).data;
  try {
    await page.goto(base);
    const frame = page.frameLocator("iframe");
    const child = page.frames().find(item => item.parentFrame());
    const back = () => frame.getByRole("button", { name: "返回", exact: true }).click();
    const tab = label => frame.getByRole("navigation").getByRole("button", { name: label, exact: true }).click();
    const detail = () => frame.locator(".detail-page");
    await frame.getByRole("navigation").getByRole("button", { name: "想法", exact: true }).waitFor();
    assert.equal(await frame.getByRole("navigation").getByRole("button").first().textContent(), "想法");
    assert.equal(await frame.getByRole("navigation").getByRole("button").first().getAttribute("aria-current"), "page");
    await frame.getByRole("combobox", { name: "筛选主题", exact: true }).click();
    await frame.getByRole("option", { name: "+ 新建主题", exact: true }).click();
    let dialog = frame.getByRole("dialog");
    await dialog.getByLabel("主题名称", { exact: true }).fill(name);
    await dialog.getByRole("button", { name: "创建主题", exact: true }).click();
    await tab("资料");
    await frame.getByRole("button", { name: "添加资料", exact: true }).click();
    dialog = frame.getByRole("dialog");
    await dialog.getByRole("button", { name: "本地文件", exact: true }).click();
    const topicControl = dialog.getByRole("combobox", { name: "放进主题", exact: true });
    await topicControl.click();
    await frame.getByRole("option", { name: "暂不归入主题", exact: true }).waitFor();
    await page.screenshot({ path: path.join(output, "controls-dropdown.png"), fullPage: true, animations: "disabled" });
    await topicControl.press("Escape");
    assert.equal(await dialog.count(), 1, "Escape closes the select before the modal");
    assert.equal(await topicControl.getAttribute("aria-expanded"), "false");
    await topicControl.press("ArrowDown");
    await topicControl.press("Home");
    await topicControl.press("End");
    await topicControl.press("Enter");
    assert.equal(await topicControl.textContent(), name);
    await dialog.locator('input[type="file"]').setInputFiles(fixture);
    await dialog.getByText("synthetic-note.md", { exact: true }).waitFor();
    await dialog.getByRole("button", { name: "收集资料", exact: true }).click();
    await detail().getByText(quote, { exact: true }).waitFor();
    assert.equal(await frame.getByRole("dialog").count(), 0); // Reading is in the main pane.
    await detail().getByRole("article").filter({ hasText: quote }).getByRole("button", { name: "记下想法", exact: true }).click();
    dialog = frame.getByRole("dialog");
    await dialog.getByLabel("想法", { exact: true }).fill("合成验收：保存后的引用可以重新定位。");
    await dialog.getByRole("button", { name: "记下想法", exact: true }).click();
    await dialog.waitFor({ state: "detached" });
    await back();
    await frame.locator(".content-row").first().waitFor();
    const topicId = await frame.getByRole("combobox", { name: "筛选主题", exact: true }).getAttribute("data-value");
    const sources = await read("management", { view: "sources", topic: topicId });
    const source = await read("source", { source_id: sources.items[0].source_id });
    const block = source.blocks.find(item => item.text === quote);
    // Model-origin suggestions arrive through the same MCP workflow as the scheduled run.
    for (let i = 1; i <= 3; i++) {
      await call("record_claim", { topic_id: topicId, statement: `自动反刍验收问题 ${i}：引用能否跨版本回看？\n\n为什么值得回看：资料变化后仍应保留证据位置。\n\n下一步：对照保存时的原文。`, claim_kind: "question", relation: "mentions", block_id: block.block_id, request_id: `${name}-auto-${i}` });
    }
    await write("generate_reviews", { topic_id: topicId });
    const pending = await read("management", { view: "thoughts", topic: topicId, status: "pending" });
    assert.equal(pending.total, 3);
    assert.ok(pending.items.every(item => item.origin === "host_model"));
    const automatic = pending.items[0];
    await tab("想法");
    await frame.getByRole("button", { name: /^待回看/ }).click();
    await frame.locator(".content-row").last().waitFor();
    assert.equal(await frame.locator(".content-row").count(), 3);
    assert.equal(await frame.getByRole("combobox", { name: "筛选主题", exact: true }).getAttribute("data-value"), topicId);
    await page.screenshot({ path: path.join(output, "management-pending.png"), fullPage: true, animations: "disabled" });
    await frame.locator(`[data-row-id="${automatic.id}"]`).click();
    await detail().getByRole("heading", { name: "为什么值得回看", exact: true }).waitFor();
    await detail().getByRole("heading", { name: "下一步", exact: true }).waitFor();
    await detail().locator(".evidence-quote button").click();
    await detail().locator("mark").waitFor();
    assert.equal(await detail().locator("mark").textContent(), quote);
    await back();
    await detail().getByText("右下角对话已关联当前内容", { exact: true }).waitFor();
    let hostEvents = await (await page.request.get(base + "/events")).json();
    assert.equal(hostEvents.filter(event => event.method === "ui/update-model-context").at(-1).params.structuredContent.claim_id, automatic.claim_id);
    assert.equal(hostEvents.some(event => event.method === "ui/message"), false, "reading never sends a message");
    await page.evaluate(() => send({ jsonrpc: "2.0", method: "ui/notifications/host-context-changed", params: { "openai/modelContext": null } }));
    await detail().getByText("对话关联已移除；点“继续聊”可重新加入", { exact: true }).waitFor();
    const eventCount = hostEvents.length;
    await child.evaluate(() => setSelection(currentSelection.data, currentSelection.title));
    await page.waitForTimeout(120);
    assert.equal((await (await page.request.get(base + "/events")).json()).length, eventCount);
    await detail().getByRole("button", { name: "继续聊这条", exact: true }).click();
    await frame.getByText("问题已放入右下角对话，可修改后发送", { exact: true }).waitFor();
    await page.screenshot({ path: path.join(output, "management-thought.png"), fullPage: true, animations: "disabled" });
    await detail().getByRole("button", { name: "稍后再看", exact: true }).click();
    await frame.locator(".content-row").first().waitFor();
    assert.equal(await frame.locator(".content-row").count(), 2);
    assert.equal(await frame.getByRole("button", { name: /^待回看/ }).getAttribute("aria-pressed"), "true");
    assert.equal(await read("management", { view: "thoughts", topic: topicId, status: "later" }).then(r => r.total), 1);
    await frame.locator(".content-row").first().click();
    await detail().getByRole("button", { name: "有启发", exact: true }).click();
    await frame.locator(".content-row").first().waitFor();
    assert.equal(await frame.locator(".content-row").count(), 1);
    await frame.locator(".content-row").first().click();
    await detail().getByRole("button", { name: "略过", exact: true }).click();
    await frame.getByRole("heading", { name: "没有找到匹配的内容" }).waitFor();
    assert.equal((await read("management", { view: "thoughts", topic: topicId, status: "processed" })).total, 2);
    await tab("输出");
    await frame.getByRole("button", { name: "新建输出", exact: true }).click();
    dialog = frame.getByRole("dialog");
    await dialog.getByLabel("标题", { exact: true }).fill(name + " 提纲");
    await dialog.getByRole("button", { name: "创建输出", exact: true }).click();
    await detail().getByRole("button", { name: "生成提纲", exact: true }).click();
    await detail().getByText("4 处引用", { exact: true }).waitFor();
    await detail().getByRole("button", { name: "导出 Markdown", exact: true }).click();
    const markdown = await frame.getByRole("dialog").locator("textarea").inputValue();
    assert.ok(markdown.includes("[^e1]"));
    await frame.getByRole("dialog").getByRole("button", { name: "关闭", exact: true }).click();
    await detail().getByRole("button", { name: /\[1\].*MCP GUI fixture/ }).click();
    await detail().locator("mark").waitFor();
    assert.equal(await detail().locator("mark").textContent(), quote);
    await back();
    await page.screenshot({ path: path.join(output, "management-output.png"), fullPage: true, animations: "disabled" });
    await back();
    await tab("资料");
    await frame.getByRole("button", { name: "添加资料", exact: true }).click();
    dialog = frame.getByRole("dialog");
    await dialog.getByRole("button", { name: "本地文件", exact: true }).click();
    await dialog.locator('input[type="file"]').setInputFiles(path.resolve("tests/fixtures/single_column.pdf"));
    await dialog.getByRole("button", { name: "收集资料", exact: true }).click();
    await detail().getByRole("button", { name: "页面图像", exact: true }).click();
    const pageImage = detail().getByRole("img");
    await pageImage.waitFor({ state: "visible" });
    assert.ok(await pageImage.evaluate(image => image.complete ? image.naturalWidth : new Promise(resolve => image.addEventListener("load", () => resolve(image.naturalWidth), { once: true }))));
    await back();
    await frame.getByLabel("搜索资料", { exact: true }).fill("across");
    await frame.getByLabel("搜索资料", { exact: true }).press("Enter");
    await frame.locator(".content-row").first().waitFor();
    assert.equal(await frame.locator(".content-row").count(), 1);
    await frame.locator(".content-row").first().click();
    await detail().getByText(quote, { exact: true }).waitFor();
    await back();
    assert.equal(await frame.getByLabel("搜索资料", { exact: true }).inputValue(), "across");
    await frame.getByLabel("搜索资料", { exact: true }).fill("");
    await frame.getByLabel("搜索资料", { exact: true }).press("Enter");
    await frame.locator(".content-row").nth(1).waitFor();
    await page.screenshot({ path: path.join(output, "management-sources.png"), fullPage: true, animations: "disabled" });
    await page.setViewportSize({ width: 390, height: 844 });
    const sizes = await child.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth }));
    assert.ok(sizes.scroll <= sizes.width + 1, JSON.stringify(sizes));
    await page.screenshot({ path: path.join(output, "management-mobile.png"), fullPage: true, animations: "disabled" });
    await page.evaluate(() => document.querySelector("iframe").contentWindow.postMessage({ jsonrpc: "2.0", method: "ui/notifications/host-context-changed", params: { theme: "dark" } }, "*"));
    await frame.locator('html[data-host-theme="dark"]').waitFor();
    await frame.getByRole("combobox", { name: "排序", exact: true }).click();
    await page.waitForTimeout(100);
    const menuBox = await frame.getByRole("listbox", { name: "排序选项", exact: true }).boundingBox();
    assert.ok(menuBox.x >= 0 && menuBox.x + menuBox.width <= 391);
    await page.screenshot({ path: path.join(output, "management-dark.png"), fullPage: true, animations: "disabled" });
    await frame.getByRole("combobox", { name: "排序", exact: true }).press("Escape");
    await page.setViewportSize({ width: 1180, height: 960 });
    const topicFilter = frame.getByRole("combobox", { name: "筛选主题", exact: true });
    await topicFilter.click();
    await frame.getByRole("option", { name: "编辑当前主题…", exact: true }).click();
    dialog = frame.getByRole("dialog", { name: "编辑主题", exact: true });
    await dialog.getByLabel("主题名称", { exact: true }).fill("Agent 研究主题");
    await dialog.getByLabel("想探索的问题", { exact: true }).fill("测试改名后的研究引用。");
    await dialog.getByRole("button", { name: "保存修改", exact: true }).click();
    await dialog.waitFor({ state: "detached" });
    assert.equal(await topicFilter.getAttribute("data-value"), topicId);
    assert.equal(await topicFilter.textContent(), "Agent 研究主题");
    await frame.locator(`[data-row-id="${source.source_id}"]`).click();
    await detail().getByRole("button", { name: "编辑资料", exact: true }).click();
    dialog = frame.getByRole("dialog", { name: "编辑资料", exact: true });
    await dialog.getByLabel("资料名称", { exact: true }).fill("资料整理验收");
    await dialog.getByRole("button", { name: "新建主题", exact: true }).click();
    const newTopic = frame.getByRole("dialog", { name: "新建研究主题", exact: true });
    await newTopic.getByLabel("主题名称", { exact: true }).fill("评估方法");
    await newTopic.getByRole("button", { name: "创建主题", exact: true }).click();
    await newTopic.waitFor({ state: "detached" });
    await dialog.getByRole("checkbox", { name: "Agent 研究主题", exact: true }).uncheck();
    assert.equal(await dialog.getByRole("checkbox", { name: "评估方法", exact: true }).isChecked(), true);
    await page.screenshot({ path: path.join(output, "source-organization.png"), fullPage: true, animations: "disabled" });
    await page.setViewportSize({ width: 390, height: 844 });
    const editorBox = await dialog.boundingBox();
    assert.ok(editorBox.x >= 0 && editorBox.x + editorBox.width <= 391);
    await page.screenshot({ path: path.join(output, "source-organization-mobile.png"), fullPage: true, animations: "disabled" });
    await dialog.getByRole("button", { name: "保存修改", exact: true }).click();
    await dialog.waitFor({ state: "detached" });
    await detail().getByRole("heading", { name: "资料整理验收", exact: true }).waitFor();
    const organized = await read("source", { source_id: source.source_id });
    assert.deepEqual(organized.blocks, source.blocks);
    assert.equal(organized.title, source.title);
    assert.equal(organized.topics.length, 1);
    assert.equal(organized.topics[0].name, "评估方法");
    await back();
    await topicFilter.click();
    await frame.getByRole("option", { name: "评估方法", exact: true }).click();
    await frame.getByLabel("搜索资料", { exact: true }).fill("资料整理验收");
    await frame.getByLabel("搜索资料", { exact: true }).press("Enter");
    await frame.locator(".content-row").first().click();
    await detail().getByRole("button", { name: "编辑资料", exact: true }).click();
    dialog = frame.getByRole("dialog", { name: "编辑资料", exact: true });
    await dialog.getByRole("button", { name: "恢复原始标题", exact: true }).click();
    await dialog.getByRole("button", { name: "保存修改", exact: true }).click();
    await detail().getByRole("heading", { name: source.title, exact: true }).waitFor();
    assert.equal((await read("source", { source_id: source.source_id })).title_is_custom, false);
    const projects = await read("projects", { topic: topicId });
    const unchanged = await read("revision", { project_id: projects[0].project_id });
    assert.equal(unchanged.markdown, markdown);
    hostEvents = await (await page.request.get(base + "/events")).json();
    assert.deepEqual(hostEvents.find(event => event.method === "ui/message").params._meta, { "openai/message": { target: "active", send: false } });
    assert.ok(hostEvents.some(event => event.method === "ui/update-model-context"));
    assert.deepEqual(failures, []);
    assert.deepEqual(iframeRequests, []);
    const report = { host: "local MCP Apps protocol test host (not Codex)", transport: "opaque iframe postMessage → real stdio MCP", topic_created: true, file_uploaded: true, exact_unicode_quote: true, inline_details_and_back: true, search_and_topic_preserved: true, host_model_suggestions_in_pending: 3, postpone_useful_dismiss_saved: true, draft_and_citation_navigation: true, pdf_image_rendered: true, markdown_export: true, host_discussion_draft: true, context_tracks_selection_and_back: true, removed_context_respected: true, thoughts_default: true, custom_select_keyboard_and_modal: true, narrow_viewport: sizes, dark_host_theme: true, iframe_network_requests: iframeRequests, javascript_errors: failures };
    Object.assign(report, { topic_renamed: true, source_renamed_and_reclassified: true, nested_topic_creation: true, title_reset: true, historical_citations_preserved: true });
    await fs.writeFile(path.join(output, "result.json"), JSON.stringify(report, null, 2));
    console.log(JSON.stringify(report, null, 2));
  } catch (error) {
    await page.screenshot({ path: path.join(output, "failure.png"), fullPage: true, animations: "disabled" });
    console.error(await page.locator("iframe").contentFrame().locator("body").innerText({ timeout: 1000 }).catch(() => "UI unavailable"));
    throw error;
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
